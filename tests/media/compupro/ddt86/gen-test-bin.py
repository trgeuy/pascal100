# Build TEST.BIN: one instance of (nearly) every 8086 opcode, each ModRM form, prefixes.
# Writes TEST.BIN and INDEX.TXT (offset: bytes).
import sys
seqs=[]
def add(*b): seqs.append(bytes(b))
modrm_forms=[0x00,0x01,0x02,0x03,0x04,0x05,0x07,0x06,  # mod 00 (06 = direct)
             0x40,0x47,0x46,                            # mod 01 disp8 (+, BP)
             0x80,0x87,0xC0,0xC7]                       # mod 10 disp16, mod 11
def m(mr):  # modrm + displacement bytes
    mod=mr>>6; rm=mr&7
    if mod==0 and rm==6: return [mr,0x34,0x12]
    if mod==1: return [mr,0xFC if rm==6 else 0x05]
    if mod==2: return [mr,0x78,0x56]
    return [mr]
# ALU groups 00-3F (reg/mem forms with each modrm, acc-imm forms)
for base in range(0,0x40,8):
    for op in range(4):
        for mr in modrm_forms: add(base+op,*m(mr|0x18))
    add(base+4,0x12); add(base+5,0x34,0x12)
for op in (0x06,0x07,0x0E,0x0F,0x16,0x17,0x1E,0x1F,0x27,0x2F,0x37,0x3F): add(op)
for op in (0x26,0x2E,0x36,0x3E): add(op,0x8A,0x07)        # segment overrides
for op in range(0x40,0x60): add(op)
for op in range(0x60,0x80): add(op,0x10)                   # Jcc + aliases
add(0x75,0xF0)                                             # backward
for op in (0x80,0x81,0x82,0x83):
    for r in range(8):
        for mr in (0x07,0x47,0x06,0xC3): add(op,*m(mr|r<<3),*( [0x12] if op!=0x81 else [0x34,0x12]))
    add(0x83,0xC0,0xFF)
for op in (0x84,0x85,0x86,0x87,0x88,0x89,0x8A,0x8B):
    for mr in modrm_forms: add(op,*m(mr|0x10))
for r in range(8):
    add(0x8C,*m(0x47|r<<3)); add(0x8C,0xC0|r<<3); add(0x8E,*m(0x07|r<<3)); add(0x8E,0xC0|r<<3)
add(0x8D,*m(0x47)); add(0x8D,*m(0x06))
for r in range(8): add(0x8F,*m(0x07|r<<3))
add(0x8F,0xC0)
for op in range(0x90,0xA0):
    if op==0x9A: add(op,0x78,0x56,0x34,0x12)
    else: add(op)
add(0xA0,0x34,0x12); add(0xA1,0x34,0x12); add(0xA2,0x34,0x12); add(0xA3,0x34,0x12)
for op in range(0xA4,0xB0):
    if op in (0xA8,): add(op,0x12)
    elif op==0xA9: add(op,0x34,0x12)
    else: add(op)
for op in (0xA4,0xA5,0xA6,0xA7,0xAA,0xAB,0xAC,0xAD,0xAE,0xAF): add(0xF3,op); add(0xF2,op)
add(0x26,0xA4); add(0xF3,0x26,0xA5); add(0x2E,0xAC)
for op in range(0xB0,0xB8): add(op,0x12)
for op in range(0xB8,0xC0): add(op,0x34,0x12)
add(0xC0,0x04,0x00); add(0xC1); add(0xC2,0x04,0x00); add(0xC3)
add(0xC4,*m(0x47)); add(0xC5,*m(0x06))
for r in range(8): add(0xC6,*m(0x07|r<<3),0x12); add(0xC7,*m(0x07|r<<3),0x34,0x12)
add(0xC8,0x04,0x00); add(0xC9); add(0xCA,0x04,0x00); add(0xCB); add(0xCC); add(0xCD,0x21); add(0xCD,0xE0); add(0xCE); add(0xCF)
for op in (0xD0,0xD1,0xD2,0xD3):
    for r in range(8): add(op,*m(0x07|r<<3)); add(op,0xC0|r<<3|1)
add(0xD4,0x0A); add(0xD5,0x0A); add(0xD4,0x08); add(0xD6); add(0xD7)
for op in range(0xD8,0xE0): add(op,*m(0x07|(op&7)<<3)); add(op,0xC1)
add(0xE0,0x10); add(0xE1,0x10); add(0xE2,0x10); add(0xE3,0x10)
add(0xE4,0x12); add(0xE5,0x12); add(0xE6,0x12); add(0xE7,0x12)
add(0xE8,0x00,0x01); add(0xE9,0x00,0xFF); add(0xEA,0x78,0x56,0x34,0x12); add(0xEB,0x10); add(0xEB,0xFE)
add(0xEC); add(0xED); add(0xEE); add(0xEF)
add(0xF0,0x87,0x07); add(0xF1,0x87,0x07); add(0xF4); add(0xF5)
for op in (0xF6,0xF7):
    for r in range(8):
        imm=[0x12] if op==0xF6 else [0x34,0x12]
        add(op,*m(0x07|r<<3),*(imm if r in (0,1) else [])); add(op,0xC0|r<<3|2,*(imm if r in (0,1) else []))
for op in range(0xF8,0xFE): add(op)
for r in range(8): add(0xFE,*m(0x07|r<<3)); add(0xFF,*m(0x07|r<<3))
add(0xFF,0xD0); add(0xFF,0xE3); add(0xFF,0x1E,0x34,0x12); add(0xFF,0x2F)
data=b''.join(seqs)
open('TEST.BIN','wb').write(data)
with open('INDEX.TXT','w') as f:
    off=0
    for s in seqs:
        f.write('%04X %s\n'%(off,' '.join('%02X'%x for x in s))); off+=len(s)
print(len(seqs),'instructions',len(data),'bytes')
