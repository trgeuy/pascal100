;	The following equates describe the double density format(s)
;	supported by this version of QGEN and can be modified as
;	required (see section V.D.10.g of Pascal-100 User's Manual):
DDTRK0	EQU	0	;Double density boot track
DDTRK1	EQU	1	;Double density first Pascal track
DDSEC1	EQU	1	;Double density lowest valid sector number
DDSECSZ	EQU	512	;Double density sector size
DDINCR	EQU	2	;Double density interleave factor for Pascal
			;area of disk

BOOT	EQU	0	;CP/M reboot address
BDOS	EQU	5	;CP/M BDOS entry address
WRBUF	EQU	9	;CP/M BDOS function to write a string
VERSION	EQU	12	;CP/M BDOS function to return version number
DRESET	EQU	13	;CP/M BDOS function to reset disk system
START	EQU	900H	;Start of Pascal-100 boot image
STACK	EQU	2000H	;STACK AREA
SRLH	EQU	3CCBH	;Z80 INSTRUCTION - SHIFT RIGHT LOGICAL REG H
SRLL	EQU	3DCBH	;Z80 INSTRUCTION - SHIFT RIGHT LOGICAL REG L
;
CR	EQU	0DH	;ASCII CHARACTERS
LF	EQU	0AH
ESC	EQU	1BH
BS	EQU	08H
SPC	EQU	20H
DEL	EQU	7FH
EOM	EQU	'$'
;
;
;
	ORG	TPA
;
;
	LXI	SP,STACK
MAIN:
	CALL	SAY$TITLE
	CALL	GET$BOOTER
	CALL	SET$PARMS
	CALL	PUT$BOOTER
	JMP	REBOOT
;
;
HOME:				;HOME DISK
	LHLD	BOOT+1
	MVI	L,18H
	PCHL
;
SELDSK:				;SELECT DISK
	LHLD	BOOT+1
	MVI	L,1BH
	PCHL
;
SETTRK:				;SET TRACK
	LHLD	BOOT+1
	MVI	L,1EH
	PCHL
;
SETSEC:				;SET SECTOR
	DCR	C		;CP/M 2 BIOS: its sectors start at 0
	LHLD	BOOT+1
	MVI	L,21H
	PCHL
;
SETDMA:				;SET DMA ADDRESS
	LHLD	BOOT+1
	MVI	L,24H
	PCHL
;
READ:				;READ A SECTOR
	LHLD	BOOT+1
	MVI	L,27H
	PCHL
;
WRITE:				;WRITE A SECTOR
	LHLD	BOOT+1
	MVI	L,2AH
	PCHL
;
CONIN:
	LHLD	BOOT+1
	MVI	L,09H
	PCHL
;
CONOUT:
	MOV	E,C		;GET CHAR IN REG E FOR BDOS
	MVI	C,2		;SET C FOR BDOS CALL
	JMP	BDOS		;CALL BDOS FOR CONOUT
;				;-----> RETURN DIRECTLY FROM BDOS
;
SAY$TITLE:			;JUST SAY WHO WE ARE
	MVI	C,WRBUF
	LXI	D,HELLO$MSG
	CALL	BDOS
	RET
;
;
GET$BOOTER:			;MAYBE A BOOTER COMES IN
	CALL	PRMSG
	DW	GET$MSG
	CALL	CK$AB		;GET DISK DRIVE RESPONSE (A/B/<RET>)
	RC			;WAS <RET>, ABORT ROUTINE
	STA	READ$DR		;STORE A/B IN MESSAGE
	CALL	PRMSG
	DW	READ$MSG
	CALL	WAIT$FOR$RET	;AND WAIT
	CALL	DO$READ
	CALL	PRMSG
	DW	GOT$MSG
	RET			;DONE
;
;
SET$PARMS:
	CALL	PRMSG		;SEE IF USER WANTS TO ALTER BOOT PARMS
	DW	PARMS$MSG
	CALL	CK$YES
	RC			;----->NO, RETURN

;	USER WANTS TO SEE OR ALTER BOOT PARMS
	MVI	A,0		;INITIALIZE CHANGES FLAG=NO CHANGES
	STA	CHANGES
	CALL	LIST$PARMS	;PRINT PARMS AND THEIR VALUES
SET$LOOP:
	CALL	PRMSG		;SEE WHICH PARM USER WANTS TO CHANGE
	DW	CHOICE$MSG
	CALL	GET$CHOICE
	JNC	SET$CHG		;--> GO CHANGE A BOOT PARAMETER

;	USER HIT <RET>, DONE WITH CHANGES
	LDA	CHANGES		;ANY CHANGES?
	ORA	A
	RZ			;-----> NO, JUST RETURN
	CALL	PRMSG		;PRINT FINAL VALUES OF BOOT PARMS
	DW	FINVAL$MSG
	CALL	LIST$PARMS
	RET			;-----> RETURN

SET$CHG:			;USER WANTS TO ALTER A BOOT PARAMETER
	CALL	PRMSG		;PROMPT FOR NEW VALUE
	DW	CHG$MSG
	CALL	PRINT$CHMSG
	CALL	RDHEX		;READ NEW VALUE INTO HL
	JC	SET$LOOP	;--> USER HIT <ESC>, DON'T STORE
	CALL	STORE$VAL	;STORE NEW VALUE IN PROPER LOCATION
	MVI	A,1		;INDICATE CHANGES IN BOOT PARAMETERS
	STA	CHANGES
	JMP	SET$LOOP	;--> LOOP
;
;
PUT$BOOTER:			;DOES THE BOOTER GO OUT?
	CALL	PRMSG
	DW	PUT$MSG
	CALL	CK$AB		;GET DISK DRIVE RESPONSE
	RC			;IF <RET>, ABORT ROUTINE
	STA	WRITE$DR		;STORE DRIVE IN MESSAGE
PUT$AGAIN:			;ELSE START TO PUT
	CALL	PRMSG
	DW	WRITE$MSG
	CALL	WAIT$FOR$RET	;AND HOLD UP
	CALL	DO$WRITE	;NOW PUT IT OUT
	CALL	PRMSG
	DW	AGAIN$MSG
	CALL	CK$YES
	JNC	PUT$AGAIN	;GUESS SO
	RET			;ALL DONE
;
;
REBOOT:				;PULL BACK CP/M
	CALL	PRMSG
	DW	REBOOT$MSG
	CALL	WAIT$FOR$RET
	JMP	BOOT
;
;
LIST$PARMS:			;LIST BOOT PARAMETERS AND THEIR VALUES
	CALL	PRMSG		;SKIP A LINE
	DW	CRLF
	MVI	A,0		;SET CHOICE=0
LIST$LOOP:
	STA	CHOICE		;STORE VALUE OF PARAMETER INDEX
	CALL	PRMSG		;START NEW LINE
	DW	CRLF
	CALL	PRINT$CHMSG	;PRINT DESCRIPTION OF THIS PARAMETER
	CALL	LOAD$VAL	;LOAD VALUE OF PARAMETER INTO HL
	CALL	WRTHEX		;PRINT VALUE IN HEX
	LDA	CHOICE		;INCREMENT PARAMETER INDEX
	INR	A
	CPI	MAX$CHOICE+1	;MORE TO DO?
	JC	LIST$LOOP	;--> YES, LOOP
	RET			;-----> NO, RETURN


PRINT$CHMSG:			;PRINT BOOT PARAMETER DESCRIPTION/PROMPT
	LXI	D,MSG$TABLE	;DE->MESSAGE ADDRESS TABLE
	LDA	CHOICE		;HL->ADDR(MSG[CHOICE])
	MOV	L,A
	MVI	H,0
	DAD	H
	DAD	D
	MOV	E,M		;DE:=ADDR(MSG[CHOICE])
	INX	H
	MOV	D,M
	MVI	C,WRBUF		;CALL CP/M TO PRINT MSG[CHOICE]
	CALL	BDOS
	RET			;-----> RETURN


GET$CHBEL:
	CALL	BELL		;RING BELL FOR BAD CHOICE

GET$CHOICE:			;GET CHOICE OF BOOT PARAMETER
	CALL	CONIN		;READ CHARACTER
	MOV	C,A		;SAVE FOR ECHO
	CALL	UCLC		;CONVERT TO UPPER CASE
	CPI	CR		;<RET>?
	JZ	GET$CHRET	;--> YES
	SUI	'A'		;CONVERT TO 0 ORIGIN, TEST
	JC	GET$CHBEL	;--> BAD CHARACTER
	CPI	MAX$CHOICE+1	;TEST
	JNC	GET$CHBEL	;--> BAD CHARACTER
	STA	CHOICE		;SAVE CHOICE
	CALL	CONOUT		;ECHO THE CHARACTER
	CMP	A		;CLEAR CARRY FLAG TO INDICATE GOOD CHOICE
	RET			;-----> RETURN

GET$CHRET:			;USER HIT <RET>
	CALL	CONOUT		;ECHO THE <RET>
	STC			;SET CARRY FLAG TO INDICATE <RET>
	RET			;-----> RETURN


;-----------------------------------------------------------------
RDHEX:				;READ NEW VALUE OF BOOT PARM IN HEX
	LXI	H,0		;NUM:=0
	SHLD	NUM
	XRA	A		;DIGITS:=0
	STA	DIGITS
	LXI	H,MAX$DIGITS	;POINT AT MAX DIGITS FIELD
	MVI	M,4		;ASSUME 4 DIGITS WILL BE ALLOWED
	LDA	CHOICE		;PARM=SYSTEM CONTROL PORT ADDRESS?
	CPI	1
	JNZ	RDHEX$LOOP	;--> NO, CONTINUE
	MVI	M,2		;FOR SYSPAD, ONLY ALLOW 2 DIGITS

RDHEX$LOOP:			;READ AND PROCESS NEXT HEX DIGIT
	CALL	CONIN		;READ CHARACTER
	CALL	RDHEX$CK	;CHECK FOR CR,ESC,BS,DEL
	CALL	UCLC		;CONVERT TO UPPER CASE
	MOV	C,A		;SAVE DIGIT FOR ECHO PRINT
	SUI	'0'		;START CHAR->NUM CONVERSION, TEST < '0'
	JC	RDHEX$LOOP	;--> LESS THAN '0', BAD CHARACTER, IGNORE
	CPI	'F'+1-'0'	;TEST IF GREATER THAN 'F'
	JNC	RDHEX$LOOP	;--> YES, BAD CHARACTER, IGNORE
	CPI	9+1		;TEST IF LESS THAN OR EQUAL '9'
	JC	RDHEX$OK	;--> IN RANGE 0..9
	CPI	'A'-'0'		;TEST IF LESS THAN 'A'
	JC	RDHEX$LOOP	;--> YES, BAD CHARACTER, IGNORE
	SUI	'A'-'0'-10	;GET VALUE OF DIGIT IN RANGE A..F
RDHEX$OK:			;VALID DIGIT FOUND, VALUE IN A
	PUSH	PSW		;SAVE REG A ACROSS CONOUT CALL
	CALL	CONOUT		;PRINT DIGIT (SAVED IN C)
	POP	PSW		;RESTORE REG A
	LHLD	NUM		;NUM:=16*NUM+DIGIT
	DAD	H
	DAD	H
	DAD	H
	DAD	H
	MOV	E,A
	MVI	D,0
	DAD	D
	SHLD	NUM
	LDA	DIGITS		;INCREMENT # OF DIGITS SO FAR
	INR	A
	STA	DIGITS
	MOV	B,A		;MOVE # DIGITS SO FAR TO REG B
	LDA	MAX$DIGITS	;PICK UP MAXIMUM ALLOWED
	CMP	B		;HIT LIMIT?
	JNZ	RDHEX$LOOP	;--> NOT YET, CONTINUE

RDHEX$LP1:			;HAVE ALL THE DIGITS WE WANT, SCAN FOR CR,ESC,BS
	CALL	CONIN		;READ CHARACTER
	CALL	RDHEX$CK	;CHECK FOR CR,ESC,BS,DEL
	JMP	RDHEX$LP1	;--> LOOP UNTIL GET CR,ESC,BS

RDHEX$CK:			;CHECK FOR CR,ESC,BS,DEL
	POP	H		;GET RETURN ADDRESS IN HL
	CPI	CR		;CR?
	JZ	RDHEX$CR	;--> YES, PROCESS <CR>
	CPI	ESC		;ESC?
	JZ	RDHEX$ESC	;--> YES, ABORT
	CPI	BS		;BS?
	JZ	RDHEX$BS	;--> YES, PROCESS <BS>
	CPI	DEL		;DEL?
	JZ	RDHEX$BS	;--> YES, TREAT AS <BS>
	PCHL			;-----> RETURN

RDHEX$CR:			;HANDLE CR
	LDA	DIGITS		;ANY DIGITS?
	ORA	A
	JZ	RDHEX$ESC	;--> NO, TREAT LIKE <ESC>
	CALL	PRMSG		;PRINT CR,LF
	DW	CRLF
	LHLD	NUM		;RETURN VALUE READ IN HL
	CMP	A		;CLEAR CARRY FLAG, INDICATING NORMAL RETURN
	RET			;-----> RETURN

RDHEX$ESC:			;HANDLE <ESC>
	STC			;SET CARRY FLAG, INDICATING <ESC>
	RET			;-----> RETURN

RDHEX$BS:			;HANDLE <BACKSPACE>
	LDA	DIGITS		;ANY DIGITS?
	ORA	A
	JZ	RDHEX$LOOP	;--> NO, IGNORE <BS>
	DCR	A		;COUNT ONE LESS DIGIT
	STA	DIGITS
	CALL	PRMSG		;ERASE LAST DIGIT
	DW	BSSPCBS
	LHLD	NUM		;NUM:=NUM DIV 16
	DW	SRLH,SRLH,SRLH,SRLH ;  (USING Z80 INSTRUCTIONS)
	DW	SRLL,SRLL,SRLL,SRLL
	JMP	RDHEX$LOOP	;--> CONTINUE
;-------------------------------------------------------------------


WRTHEX:				;PRINT VALUE OF HL IN HEX
	LDA	CHOICE		;CHOICE=SYSTEM CONTROL PORT ADDRESS?
	CPI	1
	JZ	WRTHEX$L	;--> YES, JUST PRINT ONE BYTE
	MOV	A,H		;PRINT HIGH ORDER BYTE
	PUSH	H		;SAVE HL (BECAUSE OF CONOUT CALL)
	CALL	HEXBYTE
	POP	H		;RESTORE HL
WRTHEX$L:
	MOV	A,L		;PRINT LOW ORDER BYTE
	CALL	HEXBYTE
	RET			;-----> RETURN

HEXBYTE:			;PRINT VALUE OF A IN HEX
	PUSH	PSW		;SAVE BYTE TO PRINT
	ANI	0F0H		;GET TOP NIBBLE
	RRC
	RRC
	RRC
	RRC
	CALL	HEXNIB		;PRINT TOP NIBBLE
	POP	PSW		;GET BYTE BACK
	ANI	0FH		;GET BOTTOM NIBBLE
	CALL	HEXNIB		;PRINT BOTTOM NIBBLE
	RET			;-----> RETURN

HEXNIB:				;PRINT ONE HEX DIGIT
	ADI	'0'		;START NUM->CHAR CONVERSION
	CPI	'9'+1		;IN RANGE 0..9?
	JC	HEXNIB1		;--> YES
	ADI	'A'-'0'-10	;COMPLETE NUM->CHAR CONV FOR A..F
HEXNIB1	MOV	C,A		;PRINT HEX DIGIT
	CALL	CONOUT
	RET			;-----> RETURN

LOAD$VAL:			;LOAD VALUE OF CHOSEN BOOT PARM INTO HL
	LXI	H,OFFSET$TABLE	;HL->OFFSET TABLE
	LDA	CHOICE		;HL->OFFSET OF CHOSEN PARM FROM 'START'
	MOV	C,A
	MVI	B,0
	DAD	B
	MOV	C,M		;BC:=OFFSET OF CHOSEN PARM FROM 'START'
				;  (NOTE B=0)
	LXI	H,START		;HL->CHOSEN PARAMETER IN BOOT IMAGE
	DAD	B
	MOV	E,M		;DE:=VALUE OF CHOSEN PARAMETER
	INX	H
	MOV	D,M
	XCHG			;HL:=VALUE OF CHOSEN PARAMETER
	RET			;-----> RETURN


STORE$VAL:			;STORE VALUE OF CHOSEN BOOT PARM FROM HL
	XCHG			;GET VALUE IN DE
	LXI	H,OFFSET$TABLE	;HL->OFFSET TABLE
	LDA	CHOICE		;HL->OFFSET OF CHOSEN PARM FROM 'START'
	MOV	C,A
	MVI	B,0
	DAD	B
	MOV	C,M		;BC:=OFFSET OF CHOSEN PARM FROM 'START'
				;  (NOTE B=0)
	LXI	H,START		;HL->CHOSEN PARAMETER IN BOOT IMAGE
	DAD	B
	MOV	M,E		;STORE NEW VALUE IN PARAMETER
	INX	H
	MOV	M,D
	RET			;-----> RETURN


;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
; CHECK CONSOLE INPUT FOR 'Y' OR 'N'
CK$YES:
	CALL	CONIN	;GET USER RESPONSE
	MOV	C,A	;SAVE FOR ECHO
	CALL	UCLC	;CONVERT TO UPPERCASE
	CPI	'Y'
	JZ	CK$YY
	CPI	'N'
	JZ	CK$YN
	CALL	BELL	;NEITHER 'Y' NOR 'N'
	JMP	CK$YES	;SOLICIT AGAIN, WITHOUT EVEN ECHOING
CK$YY:
	CALL	CONOUT	;GOT 'Y', ECHO
	CMP	A	;CLEAR CARRY
	RET
CK$YN:
	CALL	CONOUT	;GOT 'N', ECHO
	STC		;SET CARRY FLAG
	RET
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
; ROUTINE TO SOLICIT DRIVE (A/B) OR <RET> AND SET UP FOR SELDSK
CK$AB:
	CALL	CONIN	;GET USER CHARACTER
	MOV	C,A	;SAVE FOR ECHO
	CALL	UCLC	;CONVERT TO UPPERCASE
	CPI	'A'
	JZ	CK$ABOK
	CPI	'B'
	JZ	CK$ABOK
	CPI	CR
	JZ	CKAB$RET
	CALL	BELL	;NOT 'A', 'B' OR <RET>
	JMP	CK$AB
CK$ABOK:
	PUSH	PSW	;SAVE REG A AROUND CONOUT
	CALL	CONOUT	;GOOD RESPONSE, ECHO
	POP	PSW	;RESTORE REG A
	SUI	'A'	;SET UP CODE FOR SELDSK
	STA	DRIVENO
	ADI	'A'	;RETURN TO ASCII
	CMP	A	;CLEAR CARRY
	RET
CK$ABRET:
	CALL	CONOUT	;ECHO THE CARRIAGE RETURN
	STC		;SET CARRY FLAG TO SHOW CR
	RET
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
; RING MY BELL...
BELL:
	MVI	C,07H
	CALL	CONOUT
	RET
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
; CONVERT LOWER CASE TO UPPER
UCLC:
	cpi	'A'+20H
	RC		;RETURN IF BELOW 'a'
	CPI	'Z'+1+20H
	RNC		;OR IF ABOVE 'z'
	SUI	20H	;CONVERT TO UPPERCASE
	RET
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
;
WAIT$FOR$RET:			;HANG AROUND
	CALL	CONIN
	CPI	03H		;TEST FOR REBOOT REQUEST
	JZ	BOOT
	CPI	CR		;LEAVE WHEN READY
	JNZ	WAIT$FOR$RET
	RET
;
;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
; PRINT MESSAGE ROUTINE
PRMSG	EQU	$
	POP	H	;GET ADDR OF PARM PTR
	MOV	E,M	;AND GET PARM PTR INTO DE
	INX	H
	MOV	D,M
	INX	H	;POINT AT RETURN LOCATION
	PUSH	H	;PREPARE FOR RET
	MVI	C,WRBUF	;FINALLY, PRINT THE MESSAGE
	CALL	BDOS
	RET
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
DO$READ:			;READ IN THE BOOTER
	MVI	A,0		;INDICATE "READ"
	JMP	DO$COM		;--> MERGE WITH WRITE
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
DO$WRITE:			;WRITE OUT THE BOOTER
	MVI	A,1		;INDICATE "WRITE"

DO$COM	EQU	$		;MERGE POINT FOR READ AND WRITE
	STA	DOP		;SET READ/WRITE INDICATOR

	MVI	C,DRESET	;RESET CP/M DISK SYSTEM IN CASE
	CALL	BDOS		;  DISK CHANGE

	LDA	DRIVENO		;GET DESIRED DISK DRIVE NUMBER
	MOV	C,A
	CALL	SELDSK		;SELECT IT
	CALL	DENSITY		;CHECK ITS DENSITY
	JZ	SINDEN		;--> SINGLE DENSITY

;	DOUBLE DENSITY
	CALL	HOME		;HOME THE DRIVE

	CALL	RDSECTS		;READ/WRITE TRACK 0, SECTOR 1
	DW	START
	DB	DDTRK0,DDSEC1,1,1

	CALL	RDSECTS		;READ/WRITE REST OF TRACK 0
	DW	START+80H
	DB	DDTRK0,2,25,1	;TRACK 0 IS FM, 26 X 128, ON OUR DD DISKS

;	READ/WRITE PASCAL BLOCKS 0 AND 1
	IF	DDSECSZ/512	;512 BYTE DUB. DEN. PHYSICAL SECTORS
	CALL	RDSECTS		;READ/WRITE FIRST PASCAL BLOCK
	DW	START+26*80H
	DB	DDTRK1,DDSEC1,4,1

	CALL	RDSECTS		;READ/WRITE SECOND PASCAL BLOCK
	DW	START+30*80H
	DB	DDTRK1,DDSEC1+4*DDINCR,4,1
	ENDIF

	IF	(DDSECSZ/256) AND 1 ;256 BYTE DUB. DEN. PHYSICAL SECTORS
	CALL	RDSECTS		;READ/WRITE FIRST PASCAL BLOCK
	DW	START+26*80H
	DB	DDTRK1,DDSEC1,2,1

	CALL	RDSECTS
	DW	START+28*80H
	DB	DDTRK1,DDSEC1+2*DDINCR,2,1

	CALL	RDSECTS		;READ/WRITE SECOND PASCAL BLOCK
	DW	START+30*80H
	DB	DDTRK1,DDSEC1+4*DDINCR,2,1

	CALL	RDSECTS
	DW	START+32*80H
	DB	DDTRK1,DDSEC1+6*DDINCR,2,1
	ENDIF

	IF	(DDSECSZ/128) AND 1 ;128 BYTE DUB. DEN. PHYSICAL SECTORS
	CALL	RDSECTS
	DW	START+26*80H
	DB	DDTRK1,DDSEC1,8,DDINCR
	ENDIF

	RET			;-----> RETURN

SINDEN	EQU	$		;SINGLE DENSITY READ/WRITE
	CALL	HOME		;HOME THE DRIVE

	CALL	RDSECTS		;READ/WRITE TRACK 0
	DW	START
	DB	0,1,26,1

	CALL	RDSECTS		;READ/WRITE PASCAL BLOCKS 0 AND 1
	DW	START+26*80H
	DB	1,1,8,2
	RET			;-----> RETURN
;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
DENSITY	EQU	$		;DENSITY CHECK ROUTINE
;	ON ENTRY HL->DISK PARAMETER HEADER (DPH)

	PUSH	H		;SAVE HL
	MVI	C,VERSION	;GET VERSION OF CP/M WE'RE RUNNING
	CALL	BDOS
	MOV	A,L		;TEST FOR VERSIONS BEFORE 2.0
	ORA	A
	RZ			;-----> BEFORE CP/M 2.0, RETURN,
				;       ASSUME SINGLE DENSITY
	POP	H		;RESTORE HL

	LXI	D,10		;POINT AT DISK PARAMETER BLOCK FIELD
	DAD	D		;  OF DPH
	MOV	E,M		;SET DE->DISK PARAMETER BLOCK
	INX	H
	MOV	D,M
	LDAX	D		;GET SECTORS/TRACK FROM DISK PARM BLOCK
	CPI	26		;SET ZERO FLAG AS DENSITY INDICATOR
;				; (SINGLE DENSITY => 26 SECTORS/TRACK)
	RET			;-----> RETURN
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
; DISK READ/WRITE UTILITY
; CALL AS FOLLOWS
;	CALL	RDSECTS
;	DW	MEMADDR		;PLACE TO START READ OR WRITE
;	DB	T,I,N,D		;T=TRACK, I=INIT SECTOR, N=#SECTORS
;				;D=SECTOR INCREMENT
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
DTEMP	DS	7		;TEMP AREA FOR RDSECTS PARM LIST INSIDE
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
; TEMPLATE FOR PARAMETER LIST OF RDSECTS -- DISK READ/WRITE UTILITY
DADDR	EQU	DTEMP		;TRANSFER ADDRESS
DTRACK	EQU	DTEMP+2		;TRACK
DSECT	EQU	DTEMP+3		;SECTOR
DNSECTS	EQU	DTEMP+4		;NUMBER OF SECT TO IEAD
DSINCR	EQU	DTEMP+5		;INCREMENT FOR SECTOR
DOP	EQU	DTEMP+6		;OPERATION: 0==>READ; 1==>WRITE
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
; READ/WRITE DISK UTILITY
RDSECTS	EQU	$
	POP	H	;GET PARM LIST LOCATION
	LXI	D,DTEMP	;GET ACTUAL PARM LOCATION
	LXI	B,6	;MOVE 6 BYTES THERE (DOP FILLED BEFORE CALL)
	DB	0EDH,0B0H	;Z80 LDIR
	PUSH	H	;SAVE RETURN ADDRESS FOR RET
;
; PERFORM THE READ/WRITE AS REQUESTED
	LDA	DTRACK	;ESTABLISH TRACK
	MOV	C,A
	MVI	B,0
	CALL	SETTRK
;
; LOOP READING/WRITING SECTORS
RDSLOOP	EQU	$
	LDA	DSECT	;ESTABLISH SECTOR
	MOV	C,A
	MVI	B,0
	LDA	DSINCR	;INCREMENT TO NEXT SECTOR
	ADD	C
	STA	DSECT
	CALL	SETSEC
;
	LHLD	DADDR	;ESTABLISH DMA ADDRESS
	MOV	B,H
	MOV	C,L
	LXI	D,80H	;INCREMENT TO NEXT MEM SECTOR LOC
	DAD	D
	SHLD	DADDR
	CALL	SETDMA
;
; PERFORM DISK READ OR WRITE, ACCORDING TO THE DOP BYTE
	LDA	DOP	;GET THE COMMAND BYTE
	ORA	A	;IS IT A READ COMMAND (0)?
	JZ	RDSREAD	;YUP, GO READ
	MVI	C,1	;SET "WRITE TO DIRECTORY" (IT'S SAFER)
	CALL	WRITE	;DO A WRITE
	JMP	RDSRWBY	;AND GO ON BY

RDSREAD	EQU	$	;HERE FOR A READ
	CALL	READ
RDSRWBY	EQU	$	;DONE READING OR WRITING
	CPI	0	;CHECK FOR DISK ERROR ON RD/WR
	JNZ	DISKERR	;DISK ERROR; DO SOMETHING
	LDA	DNSECTS	;SEE IF DONE
	DCR	A
	JZ	RDSOUT
	STA	DNSECTS	;NOT DONE
	JMP	RDSLOOP	;GO READ NEXT SECTOR
;
RDSOUT	EQU	$
	RET
