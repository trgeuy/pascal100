;----------------------------------------------------------------------------+
; THIS MODULE CONSISTS OF TWO PARTS, SB AND QB.                              | 
;                                                                            |
; SB IS THE PASCAL-100 "SOFT BOOT" (SEE SECTION V.C OF THE PASCAL-100 USER'S |
; MANUAL FOR A DESCRIPTION OF THE BOOT PROCESS.)                             |
; AFTER IT EXECUTES IT IS OVERLAYED BY PASCAL OPERATING SYSTEM TABLES.       |
;                                                                            |
; QB ("QUARTERBACK") IS THE PASCAL-100 RESIDENT MICROENGINE/Z80 INTERFACE    |
; ROUTINE.  IT IS USED TO TRANSFER CONTROL TO THE MICROENGINE UPON           |
; INITIALIZATION, AND SUBSEQUENTLY RECEIVES CONTROL FROM THE MICROENGINE WHEN|
; THE MICROENGINE WOULD LIKE A FUNCTION PERFORMED BY THE Z80.  IT RETURNS    |
; CONTROL TO THE MICROENGINE USING THE PASCAL-100 SYSTEM CONTROL PORT.       |  
;----------------------------------------------------------------------------+

 
; THE FOLLOWING EQUATES CONTROL THE DEFAULT VALUES OF VARIOUS PARAMETERS  
; RELEVANT TO THE PASCAL-100 BOOT PROCESS.  THE DEFAULT VALUES ARE ASSEMBLED
; INTO A PARAMETER BLOCK AT OFFSET 3 IN THIS MODULE (SEE BELOW).  THE SIMPLEST
; WAY TO CHANGE THESE VALUES IS TO USE THE QGEN UTILITY SUPPLIED BY DIGICOMP
; ON THE "CP/M FILES" DISTRIBUTION DISKETTE.

MEMTOP  EQU     64*512          ;WORD ADDRESS OF TOP OF MEMORY AVAILABLE FOR
;                               ;  PASCAL (ADDRESS OF FIRST UNUSABLE WORD)    
SYSPAD  EQU     0D0H            ;SYSTEM CONTROL PORT ADDRESS    
;                               ; (THIS MUST BE EVEN AND MUST AGREE WITH
				;  SETTING OF DIP SWITCHES ON Z80 BOARD)   
MMOPAD  EQU     SYSPAD+1        ;MEMORY MAP OUTPUT PORT ADDRESS   
FLAGS	EQU	1		;DISK FORMAT FROM SELDSK
SERIAL	EQU	'0'		;SBQB SERIAL NUMBER
BIOSLP	EQU	480H		;LOAD POINT FOR SYSTEM.Z80BIOS, IF PRESENT
CODELP	EQU	0		;LOAD POINT FOR SYSTEM.Z80CODE, IF PRESENT
;				;  (MUST BE EVEN)
CODETB	EQU	0		;ADDRESS OF USER FUNCTION JUMP TABLE
;				;  (=0 IF NO USER FUNCTIONS)
CODEND	EQU	0A00H		;OVERALL END OF Z80 CODE AREA
BUFADR	EQU	0800H		;512 BYTE SECTOR BUFFER
;				;  (START OF MICROENGINE AREA)


; DEFAULT DISK PARAMETERS:
LOTRAK	EQU	0		;LOWEST VALID TRACK NUMBER
HITRAK	EQU	76		;HIGHEST VALID TRACK NUMBER
STTRAK	EQU	1		;FIRST USED TRACK (BLOCK 0 STARTS HERE)
LOSECT	EQU	1		;LOWEST VALID SECTOR NUMBER
HISECT	EQU	26		;HIGHEST VALID SECTOR NUMBER
SECSIZ	EQU	128		;SECTOR SIZE (MUST BE <= 512)
TRTBAD	EQU	0		;SECTOR TRANSLATE TABLE ADDRESS
				;  0 => STANDARD DOUBLE INTERLEAVE
OFFSET	EQU	6		;INTER-TRACK SECTOR OFFSET
PB1TRK	EQU	0		;PART 1 OF PASCAL BOOT: TRACK
PB1SEC	EQU	22		;                       FIRST SECTOR
PB1NO	EQU	5		;			NUMBER OF SECTORS
PB1INC	EQU	1		;			INTERLEAVE
PB2TRK	EQU	1		;PART 2 OF PASCAL BOOT: TRACK
PB2SEC	EQU	1		;                       FIRST SECTOR
PB2NO	EQU	8		;			NUMBER OF SECTORS
PB2INC	EQU	2		;			INTERLEAVE


; THE FOLLOWING EQUATES DEFINE Z80 INSTRUCTION OPERATION CODES 
; THAT ARE NOT KNOWN BY THE STANDARD CP/M ASSEMBLER. 
; THE ORDER OF THE BYTES IS REVERSED SO THAT THE ORDER WILL BE CORRECT
; WHEN ASSEMBLED BY 'DW'.
  
LDBC    EQU     4BEDH           ;Z80 "LD BC,(NN)"  
LDDE    EQU     5BEDH           ;Z80 "LD DE,(NN)"    
STBC    EQU     43EDH           ;Z80 "LD (NN),BC"    
STDE    EQU     53EDH           ;Z80 "LD (NN),DE"      
LDIR    EQU     0B0EDH          ;Z80 "LDIR"  
LDDR	EQU	0B8EDH		;Z80 "LDDR"
OUTCA   EQU     79EDH           ;Z80 "OUT (C),A"  
BIT0A	EQU	47CBH		;Z80 "BIT 0,A"


; THE FOLLOWING EQUATES DEFINE THE VALUES OF BYTES WRITTEN TO THE PASCAL-100
; SYSTEM CONTROL PORT.
TOMECOD EQU     80H             ;BYTE TO TRANSFER CONTROL TO MICROENGINE  
MMMEEN  EQU     0C0H            ;BYTE TO ENABLE MEMORY MAP FOR MICROENGINE
MMUPCOD EQU     0C5H            ;BYTE TO SELECT UPPER HALF OF MEMORY MAP
;                               ;  FOR LOADING


; Pascal-100 boot code addresses:      

SBORG   EQU     280H            ;ORIGIN OF SOFT BOOT/QB INTERFACE (THIS CODE)
BIOSORG EQU     480H            ;ORIGIN OF BIOS
CONOUT	EQU	BIOSORG+12	;BIOS CONSOLE OUTPUT ROUTINE
SELDSK	EQU	BIOSORG+27	;BIOS SELECT DISK ROUTINE
SETTRK  EQU     BIOSORG+30      ;BIOS SET TRACK ROUTINE
SETSEC  EQU     BIOSORG+33      ;BIOS SET SECTOR ROUTINE
SETDMA  EQU     BIOSORG+36      ;BIOS SET MEMORY ADDRESS ROUTINE
DSKREAD EQU     BIOSORG+39      ;BIOS DISK READ ROUTINE
PBORG   EQU     5000H           ;ORIGIN/LOAD POINT OF PASCAL BOOT 
PBORG1	EQU	PBORG+200H	;LOAD POINT FOR SECOND PART OF PASCAL BOOT
PBORGPG EQU     PBORG/800H      ;2K PAGE NUMBER OF PBORG (USED BY MAP1F8D0) 
INITMMI	EQU	PBORG1		;LOAD POINT OF INITIAL MEMORY MAP IMAGE


; Workarea for SB (Soft boot): 

SBWORK  EQU     3800H           ;ADDRESS OF 256 BYTES OF RAM AVAILABLE FOR   
;                               ;SOFT BOOT.  MUST BE OF THE FORM X800H, WHERE
;                               ; X IS 1,3,5,7,9,B,D OR F.  MUST NOT CONFLICT
;                               ; WITH ANY OTHER USAGE.
SBWKPG  EQU     SBWORK/800H     ;2K PAGE NUMBER OF SBWORK (USED BY MAP1F8D0) 
SBSTACK EQU     SBWORK+0D0H     ;STACK AREA FOR SOFT BOOT (GROWS BACKWARDS)
MEINIT  EQU     SBWORK+0D0H     ;MICROENGINE INITIALIZATION WORD
;                               ;WORKAREA USED BY RDSECTS ROUTINE: 
DTRACK  EQU     SBWORK		;  TRACK TO READ FROM 
DSECT   EQU     SBWORK+1        ;  INITIAL SECTOR TO READ FROM
DNSECTS EQU     SBWORK+2        ;  NUMBER OF SECTORS TO READ 
DSINCR  EQU     SBWORK+3        ;  SECTOR NUMBER INCREMENT
DADDR	EQU	SBWORK+4	;  MEMORY ADDRESS TO READ INTO
SBPBK	EQU	SBWORK+6	;  WORKING COPY OF DISK I/O PARAMETER BLOCK
SECSIZE	EQU	SBPBK+10	;  SECTOR SIZE FIELD
BOOTP1	EQU	SBPBK+16	;  DISK I/O BOOT PARMS - FIRST READ
BOOTP2	EQU	SBPBK+20	;  DISK I/O BOOT PARMS - SECOND READ

 
; Stack size for QB (Stack can be used by BIOS, user Z80 functions too.)

QBSTKLN EQU     40              ;40 BYTES


; The following is the Pascal-100 Z80/Microengine communication area,       
; called ZMCOM.  It resides at location 80H.

;     +-------------+ 
;     |             |       
	ORG     80H ;
;     |             | 
;     +-------------+ 

ZMCOM   EQU     $               ;Z80/MICROENGINE COMMUNICATION AREA   
ZMEMTOP DS      2               ;WORD ADDR OF TOP OF MEMORY (1ST UNUSABLE WORD)
ZSYSPAD DS      2               ;SYSTEM CONTROL PORT ADDRESS
ZCONFIG	DS	4		;SYSTEM CONFIGURATION INFORMATION
ZFLAGS	EQU	ZCONFIG		;    FLAGS
;----------------------------------------------------------------------------+
;	BIT 0: ON IF "SPECIFIED DISKS" (I.E. CP/M 2.X BIOS)                  |
;----------------------------------------------------------------------------+
ZSERIAL	EQU	ZCONFIG+2	;    SBQB SERIAL NUMBER
ZBIOSLP DS      2               ;LOAD POINT FOR SYSTEM.Z80BIOS, IF PRESENT   
;				;  (MUST BE EVEN)
ZCODELP DS      2               ;LOAD POINT FOR SYSTEM.Z80CODE, IF PRESENT
;				;  (MUST BE EVEN)  
ZCODETB	DS	2		;ADDRESS OF USER FUNCTION JUMP TABLE
;				;  (=0 IF NO USER FUNCTIONS)
ZCODEND	DS	2		;OVERALL END OF Z80 CODE AREA
;				;  (MICROENGINE AREA STARTS HERE)
ZBUFBAD	DS	2		;BYTE ADDRESS OF DISK I/O SECTOR BUFFER
ZDIOPAD	DS	2		;WORD ADDRESS OF DISK I/O PARAMETER BLOCK
Z80FCTN DS      2               ;REQUESTED Z80 FUNCTION
;----------------------------------------------------------------------------+
BIOSTOP EQU     19              ;HIGHEST VALID BIOS FUNCTION REQUEST CODE    | 
SPECBOT	EQU	20		;LOWEST "QB SPECIAL" FUNCTION REQUEST CODE   |
Z80BOT	EQU     30		;LOWEST USER FUNCTION REQUEST CODE           |
;                               ;FIRST BYTE OF USER FUNCTION JUMP TABLE GIVES|
;                               ;HIGHEST VALID USER FUNCTION REQUEST CODE    |
;----------------------------------------------------------------------------+ 
ZRTCODE DS      2               ;RETURN CODE FROM Z80 TO MICROENGINE
;----------------------------------------------------------------------------+ 
OKCODE  EQU     0               ;VALUE OF ZRTCODE ON NORMAL RETURN FROM Z80  | 
;                               ;OTHER VALUES CAN BE SET BY CALLED ROUTINE.  |
;----------------------------------------------------------------------------+
ZREGA   DS      2               ;REGISTER A (IN LOW ORDER (I.E. FIRST) BYTE)
ZREGBC  DS      2               ;REGISTERS B,C (C IN LOW ORDER BYTE)
ZREGDE  DS      2               ;REGISTERS D,E (E IN LOW ORDER BYTE)
ZREGHL  DS      2               ;REGISTERS H,L (L IN LOW ORDER BYTE)     
ZX      DS      2               ;TWO WORDS FOR GENERAL COMMUNICATION
ZY      DS      2               ;...
ZINTR   DS      2               ;ONE WORD FOR INTERRUPT COMMUNICATION  
ZBUFFER	DS	128		;DISK SECTOR BUFFER
ZMMI    DS      64*2            ;64 WORDS FOR MEMORY MAP IMAGE
;                               ;  ASSUMING EXTENDED MAP IS BEING USED,
;                               ;  LOW ORDER 9 BITS OF EACH WORD GIVE MEMORY
;                               ;  MAP CONTENTS FOR THE CORRESPONDING 2K BYTE
;                               ;  PAGE.  IF STANDARD MAP IS BEING USED, BOTTOM
;                               ;  2 AND TOP 3 BITS ARE IGNORED, AND THE WORD  
;                               ;  CORRESPONDING TO THE LAST 2K IN EACH 8K PAGE
;                               ;  GIVES THE MAP CONTENTS FOR THE 8K PAGE.
ZMCOMND EQU     $               ;END OF Z80/MICROENGINE COMMUNICATION AREA  

ZMCOMLN EQU     $-ZMCOM         ;LENGTH OF Z80/MICROENGINE COMMUNICATION AREA 


; The following area is reserved for permanently resident UCSD Pascal system 
; tables.  It starts at decimal address 422 (word 211). (Hex byte address 1A6)
  
;     +-------------+   
;     |             |   
	ORG     422 ;  
;     |             | 
;     +-------------+ 

PTABLES EQU     $               ;RESIDENT PASCAL TABLES START HERE
	
	IF      (PTABLES-ZMCOMND) AND 8000H  ;TEST IF PTABLES>ZMCOMND
         ASSEMBLY ERROR HERE MEANS ZMCOM AREA EXCEEDS ALLOCATED SPACE        
	ENDIF
	
	DS      177*2           ;LEAVE SPACE FOR 177 WORDS
PTABLND EQU     $               ;END OF SPACE RESERVED FOR PASCAL TABLES


; The Pascal-100 soft boot (SB) is ORG'd back to start at location SBORG, which
; is in the middle of the area reserved for Pascal tables.  This is done to 
; save space.  The resident part of SBQB, the QB Z80/Microengine interface
; routine, which immediately follows SB, should start AFTER the end of the   
; Pascal table area.  (This is tested at QBORG, below.)
 
;     +---------------+     
;     |               |    
	ORG     SBORG ;   
;     |               |  
;     +---------------+  

;                               ;SOFT BOOT (SB) STARTS HERE

	JMP     SBOOT           ;-----> BRANCH AROUND PARAMETER BLOCK


PARMBLK EQU     $               ;PARAMETER BLOCK CONTAINING VALUES RELEVANT TO 
;                               ;THE PASCAL-100 BOOT PROCESS.  THE DEFAULTS
;                               ;FOR THESE VALUES ARE DEFINED ABOVE. THE VALUES
;                               ;CAN BE CHANGED USING THE QGEN UTILITY PROGRAM
;                               ;SUPPLIED BY DIGICOMP.

        DW      MEMTOP          ;WORD ADDRESS OF TOP OF MEMORY AVAILABLE FOR 
;                               ;  PASCAL (ADDRESS OF FIRST UNUSABLE WORD)    
	DW      SYSPAD          ;ADDRESS OF PASCAL-100 SYSTEM CONTROL PORT 
	DW	FLAGS		;CONFIGURATION FLAGS
	DB	1,SERIAL	;SBQB SERIAL NUMBER
	DW      BIOSLP          ;LOAD POINT OF SYSTEM.Z80BIOS, IF PRESENT
;				;  (MUST BE EVEN)
	DW	CODELP		;LOAD POINT OF SYSTEM.Z80CODE, IF PRESENT
;				;  (MUST BE EVEN)
	DW	CODETB		;ADDRESS OF USER FUNCTION JUMP TABLE
;				;  (=0 IF NO USER FUNCTIONS)
	DW	CODEND		;OVERALL END OF Z80 CODE AREA
;				;  (START OF MICROENGINE AREA)
	DW	BUFADR		;BYTE ADDRESS OF DISK I/O SECTOR BUFFER
MMOPORT DW      MMOPAD          ;MEMORY MAP OUTPUT PORT ADDRESS (=SYSPAD+1)


SBOOT	EQU	$
	LXI     SP,SBSTACK      ;SET UP SOFT BOOT STACK

	LXI     B,18            ;SET FIRST 9 WORDS  
	LXI     D,ZMCOM         ;  OF Z80/MICROENGINE COMMUNICATION AREA
	LXI     H,PARMBLK       ;  FROM PARAMETER BLOCK
	DW      LDIR            ;  USING Z80 LDIR (DW TO ALLOW CP/M ASSEMBLER)

	MVI	C,0		;SELECT DISK 0
	CALL	SELDSK		;...

	LDA	ZFLAGS		;PICK UP CONFIGURATION FLAGS
	DW	BIT0A		;SEE IF "SPECIFIED DISKS"
	JNZ	SBOOT1		;--> YES, HL SET BY SELDSK TO POINT AT
;				;    PASCAL-100 DISK I/O PARAMETER BLOCK
	LXI	H,DIOPBK	;SET DEFAULT DISK I/O PARAMETER BLOCK

SBOOT1	EQU	$
	MOV	A,H		;SET WORD ADDRESS OF DISK PARM BLOCK
	ORA	A		;CLEAR CARRY FLAG
	RAR			;ROTATE RIGHT, TOP BIT=0,BOTTOM BIT->CARRY
	STA	ZDIOPAD+1
	MOV	A,L
	RAR			;ROTATE RIGHT, CARRY->TOP BIT
	STA	ZDIOPAD

	LXI	D,SBPBK		;GET WORKING COPY OF DISK I/O PARAMETER
	LXI	B,24		;  BLOCK
	DW	LDIR

;	PFBOOT HAS READ PART 1 OF THE PASCAL BOOT TO PBORG, IN FM.

	LXI	H,INITMMI	;MOVE INITIAL MEMORY MAP IMAGE INTO PLACE
	LXI	D,ZMMI
	LXI	B,128
	DW	LDIR

	LXI	H,BOOTP2	;SET HL->SECOND RDSECTS PARM SEQUENCE
        CALL    RDSECTS         ;READ PASCAL BLOCKS 0,1
	DW	PBORG1		;  INTO PLACE FOR REST OF PASCAL BOOT
        
	CALL    MAP1F8D0        ;MAP MICROENGINE INITIALIZATION WORD TO A
;                               ;  PLACE THAT'S GUARANTEED TO BE THERE
;                               ;  (MEINIT, DEFINED ABOVE)

	LXI     H,PBORG/2	;SET WORD ADDR OF MICROENGINE INITIALIZATION INFO
	SHLD    MEINIT          ;  INTO MICROENGINE INITIALIZATION WORD
;                               ;  (WHICH THE MICROENGINE THINKS IS AT 1F8D0)

	LXI     SP,QBSTACK      ;SETUP QB STACK  

	JMP     TOMICRO         ;----> JUMP INTO QB LOOP TO FIRE UP MICROENGINE


; RDSECTS subroutine   
; Utility to read a sequence of sectors from any track to any memory location.
; Calling sequence:
;       CALL    RDSECTS
;       DW      MEMORY ADDRESS TO READ INTO
;	On entry HL points at the following:
;       DB      TRACK, INITIAL SECTOR, # OF SECTORS, INCREMENT BETWEEN SECTORS

RDSECTS EQU     $

; Move parameters to workarea
	LXI     D,DTRACK         ;GET ADDRESS OF WORKAREA  
	LXI     B,4             ;MOVE PARAMETERS TO WORKAREA
	DW      LDIR            ;  USING Z80 LDIR (DW TO ALLOW CP/M ASSEMBLER)
;	now DE->DADDR, BC=0
	POP	H		;POINT AT IN-LINE PARAMETER
	MVI	C,2		;MOVE IT TO WORKAREA
	DW	LDIR
	PUSH	H		;SET NEW RETURN ADDRESS IN STACK
	
; Establish the track to read from
        LDA     DTRACK          ;GET TRACK # FROM WORKAREA  
	MOV     C,A             ;MOVE TO B,C
	MOV     B,0             ;...  
	CALL    SETTRK          ;CALL BIOS SET TRACK ROUTINE 
	 
; Loop reading sectors
RDSLOOP EQU     $
; Establish the sector to read from, incrementing sector # for next time
	LDA     DSECT           ;GET SECTOR # FROM WORKAREA 
	MOV     C,A             ;MOVE TO B,C
	MVI     B,0             ;...
	LDA     DSINCR          ;GET SECTOR INCREMENT FROM WORKAREA  
	ADD     C               ;INCREMENT SECTOR # IN WORKAREA
	STA     DSECT           ;...
	CALL    SETSEC          ;CALL BIOS SET SECTOR ROUTINE
 
; Establish DMA address, incrementing memory address for next time
	LHLD    DADDR           ;GET MEMORY ADDRESS FROM WORKAREA   
	MOV     B,H             ;MOVE TO B,C
	MOV     C,L             ;...
	DW	LDDE,SECSIZE	;MEMORY ADDRESS INCREMENT IS SECTOR SIZE
	DAD     D               ;INCREMENT MEMORY ADDRESS IN WORKAREA
	SHLD    DADDR           ;...
	CALL    SETDMA          ;CALL BIOS SET DMA ROUTINE

; Do the disk read
	CALL    DSKREAD         ;CALL BIOS DISK READ ROUTINE
        CPI     0               ;DISK READ ERROR?
	JNZ     RDSERR          ;--> YES, ERROR

; Test to see if we're done 
	LDA     DNSECTS         ;GET # OF SECTORS LEFT TO READ
	DCR     A               ;DECREMENT BY 1
	RZ                      ;-------> ALL DONE, RETURN FROM RDSECTS  
	
; Not done yet
	STA     DNSECTS         ;STORE NUMBER OF SECTORS LEFT TO READ
	JMP     RDSLOOP         ;--> GO READ NEXT SECTOR
	

; Disk read error 
RDSERR  EQU     $
	MVI	C,'e'		;DISK ERROR, PRINT MESSAGE
	CALL	CONOUT
	MVI	C,'0'
	CALL	CONOUT
	HLT                     ;QUIT HERE 
	 


; MAP1F8D0 
; SUBROUTINE TO USE THE PASCAL-100 MEMORY MAP TO MAP MICROENGINE INITIALIZATION
; LOCATION 1F8D0 TO A MORE REASONABLE LOCATION.  ALSO MAPS PASCAL
; BOOT TO ITSELF, AND ZEROTH PAGE TO ITSELF.  NO OTHER PAGES ARE MAPPED,
; SO PASCAL BOOT IS EXPECTED TO DISABLE MEMORY MAP AS SOON AS POSSIBLE,
; UNTIL FURTHER LOADING OF THE MEMORY MAP IS ACCOMPLISHED.  NOTE THAT
; WE MAY BE MAPPING 2K PAGES OR 8K PAGES - CODE WORKS FOR EITHER CASE.

MAP1F8D0 EQU    $
	LDA     MMOPORT         ;LOAD C REGISTER WITH MEMORY MAP OUTPUT PORT
	MOV     C,A             ;  ADDRESS 
	
; MAP 0TH PAGE TO ITSELF
	MVI	A,255-0		;LOAD A REGISTER WITH DESIRED MAP CONTENTS
;				;  (INVERTED)
	MVI	B,0 SHL 3 +1	;LOAD B REGISTER WITH MAP ENTRY ADDRESS
;				;  (WITH BOTTOM BIT INVERTED->TOP OF CONTENTS)
	DW	OUTCA		;Z80 OUT (C),A TO LOAD MEMORY MAP

; MAP 2 PAGES CONTAINING PASCAL BOOT TO THEMSELVES
	MVI     A,255-PBORGPG	;LOAD A REGISTER WITH DESIRED MAP CONTENTS
	MVI     B,PBORGPG SHL 3 +1 ;LOAD B REGISTER WITH MAP ENTRY ADDRESS
;				;  (WITH INVERTED BOTTOM BIT->TOP OF CONTENTS)
	DW      OUTCA           ;Z80 OUT (C),A TO LOAD MEMORY MAP
	MVI	A,255-(PBORGPG+1) ;DO THE SAME THING FOR THE 2ND PAGE
	MVI	B,(PBORGPG+1) SHL 3 +1;...
	DW	OUTCA		;...
	
; ENABLE MEMORY MAP FOR MICROENGINE
	DCR     C               ;SET C REGISTER TO SYSTEM CONTROL PORT ADDRESS
;                               ;  (WHICH IS 1 LESS THAN MEMORY MAP OUTPUT PORT
;                               ;   ADDRESS)
        MVI     A,MMMEEN        ;SET A REGISTER TO CODE TO ENABLE MEMORY MAP
;                               ;  FOR MICROENGINE  
        DW      OUTCA           ;Z80 OUT (C),A TO WRITE TO SYSTEM CONTROL PORT

; MAP PAGE CONTAINING 1F8D0 TO SBWORK PAGE
	MVI     A,MMUPCOD       ;SET A REGISTER TO CODE TO SELECT UPPER HALF
	;                       ;  OF MEMORY MAP FOR LOADING
	DW      OUTCA           ;Z80 OUT (C),A TO WRITE TO SYSTEM CONTROL PORT
	INR     C               ;RESET C REGISTER TO MEMORY MAP OUTPUT PORT
	MVI     A,255-SBWKPG	;LOAD A REGISTER WITH DESIRED MAP CONTENTS
;				;  (INVERTED)
	MVI     B,31 SHL 3 +1	;LOAD B REGISTER WITH MAP ENTRY ADDRESS
;				;  (WITH INVERTED BOTTOM BIT->TOP OF CONTENTS)
	DW      OUTCA           ;Z80 OUT (C),A TO LOAD MEMORY MAP
	
; RETURN TO CALLER
	RET                     ;-----> RETURN FROM MAP1F8D0  
	 
;                                                                             |
;       END OF SOFT BOOT SECTION OF SBQB                                      |
;-----------------------------------------------------------------------------+

;-----------------------------------------------------------------------------+
;       START OF QB SECTION OF SBQB - RESIDENT MICROENGINE/Z80 INTERFACE      |
;                                                                             |
 
	ORG	$-QBSTKLN	;ORG BACK TO LEAVE ROOM FOR QB STACK
QBORG   EQU     $		;ORIGIN OF RESIDENT Z80/MICROENGINE 
;                               ;INTERFACE ROUTINE     

	IF      (QBORG-PTABLND) AND 8000H   ;TEST QBORG>PTABLND 
	ASSEMBLY ERROR HERE INDICATES OVERLAP BETWEEN PASCAL TABLES AND QB
	ENDIF

; QB STACK AREA: 
	
	DS      QBSTKLN         ;LEAVE SPACE FOR QB STACK  
QBSTACK EQU     $               ;  (STACK CAN BE USED BY BIOS AND
;                               ;   USER FUNCTIONS TOO)


;	DEFAULT DISK I/O PARAMETER BLOCK:
	ORG	($+($ MOD 2))	;MAKE SURE WE'RE ON A WORD BOUNDARY
DIOPBK	EQU	$		;DEFAULT DISK I/O PARAMETER BLOCK
	DW	LOTRAK		;LOWEST VALID TRACK NUMBER
	DW	HITRAK		;HIGHEST VALID TRACK NUMBER
	DW	STTRAK		;FIRST USED TRACK (BLOCK 0 STARTS HERE)
	DW	LOSECT		;LOWEST VALID SECTOR NUMBER
	DW	HISECT		;HIGHEST VALID SECTOR NUMBER
	DW	SECSIZ		;SECTOR SIZE (MUST BE <= 512)
	DW	TRTBAD		;SECTOR TRANSLATE TABLE ADDRESS
	DW	OFFSET		;INTER-TRACK SECTOR OFFSET
	DB	PB1TRK,PB1SEC,PB1NO,PB1INC  ;PARMS FOR SOFT BOOT 1ST READ
	DB	PB2TRK,PB2SEC,PB2NO,PB2INC  ;  FOR 2ND READ


; QB ("Quarterback") - resident Microengine/Z80 interface routine
;    Initial entry from soft boot is at label TOMICRO.
;    Subsequent calls from Microengine resume execution at label FROMMICRO    

QB      EQU     $               ;Top of QB loop          
 
; Pick up function request code from communication area  
	LDA     Z80FCTN         ;GET REQUESTED Z80 FUNCTION
	MOV     E,A             ;COPY INTO D,E FOR LATER USE 
	MVI     D,0             ;...
	
; DECIDE IF IT'S A BIOS FUNCTION REQUEST, A "QB SPECIAL" FUNCTION REQUEST, OR
; A USER FUNCTION REQUEST.  SET H,L TO POINT TO APPROPRIATE JUMP TABLE.
	LXI     H,BIOSORG       ;SET H,L TO START OF BIOS JUMP TABLE 
	CPI     BIOSTOP+1       ;IS IT A BIOS FUNCTION CALL? 
	JC      QB1             ;--> YES, CONTINUE
	LXI	H,QBSPCTB	;SET HL TO START OF "QB SPECIAL" JUMP TABLE
	CPI	Z80BOT		;IS IT A "QB SPECIAL" FUNCTION CALL?
	JC	QB1		;--> YES, CONTINUE
	LHLD    ZCODETB         ;SET H,L FOR USER FUNCTION JUMP TABLE

; PROCESS USER FUNCTION REQUEST
	MVI	A,0		;TEST IF ANY USER FUNCTIONS PRESENT
	CMP     H               ;...
	JZ      QBNOZ80         ;--> NOT PRESENT, ERROR
	MOV     A,M             ;GET HIGHEST VALID REQUEST CODE FROM TABLE   
	CMP     E               ;CHECK IF REQUEST IS IN RANGE
	JC      QBBADFN         ;--> TOO HIGH, ERROR
	LXI     B,-3*Z80BOT+1	;BIAS H,L TO ACCOUNT FOR NON-ZERO ORIGIN OF
        DAD     B               ;  TABLE INDEX, AND FIRST BYTE OF TABLE
	
; At this point H,L -> "virtual" origin of jump table (position of 0th entry)
;               D,E contains the function request code
QB1     EQU     $
	
; Compute function entry address, setup return address and entry address on
; stack.  (This is done so that function can be entered without using any
; registers.)
	DAD     D               ;ADD 3*FUNCTION REQUEST CODE TO TABLE BASE     
	DAD     D               ;...
	DAD     D               ;...
	LXI     B,QB2           ;PUSH RETURN ADDRESS FOR FUNCTION TO BE CALLED
	PUSH    B               ;  ON STACK 
	PUSH    H               ;PUSH ADDRESS OF FUNCTION TO BE CALLED ON STACK
	
	
; Initialize return code - this can be changed by called function  
	LXI     H,OKCODE        ;INDICATE NORMAL RETURN  
	SHLD    ZRTCODE         ;...

; Load Z80 registers from their counterparts in ZMCOM communication area 
        LDA     ZREGA           ;LOAD A REGISTER
	DW      LDBC,ZREGBC     ;LOAD BC REGISTERS
	DW      LDDE,ZREGDE     ;LOAD DE REGISTERS
	LHLD    ZREGHL          ;LOAD HL REGISTERS
	
; Enter desired function via address on top of stack
	RET                     ;ENTER DESIRED FUNCTION

QB2     EQU     $               ;RETURN POINT FROM CALLED FUNCTION

; STORE Z80 REGISTERS INTO THEIR COUNTERPARTS IN ZMCOM COMMUNICATION AREA
	DW	STBC,ZREGBC	;STORE BC REGISTERS
	DW	STDE,ZREGDE	;STORE DE REGISTERS
	SHLD    ZREGHL          ;STORE HL REGISTERS
	MOV     L,A             ;STORE A REGISTER
	MVI     H,0             ;...WITH TOP BYTE 0
	SHLD    ZREGA           ;...

; Transfer control back to Microengine 
; (Soft boot enters QB here for first transfer of control to Microengine)
TOMICRO EQU     $
	LDA     ZSYSPAD         ;GET SYSTEM CONTROL PORT ADDRESS
	MOV     C,A             ;...IN REGISTER C
	MVI	A,TOMECOD	;WRITE "TO MICROENGINE" CODE
	DW	OUTCA		;...TO SYSTEM CONTROL PORT
				;(THIS TRANSFERS CONTROL TO THE MICROENGINE)

FROMMICRO EQU   $               ;RESUME POINT WHEN NEXT CALLED BY MICROENGINE
	JMP     QB              ;--> JUMP TO TOP OF LOOP TO PROCESS REQUEST


; ERROR CONDITIONS 
QBNOZ80 EQU     $               ;FUNCTION CODE IN SYSTEM.Z80CODE RANGE,
;                               ;  WITH SYSTEM.Z80CODE NOT PRESENT
	HLT                     ;STOP RIGHT HERE
	
QBBADFN EQU     $               ;FUNCTION CODE HIGHER THAN MAXIMUM SPECIFIED
;				;  IN SYSTEM.Z80CODE
	HLT			;STOP


; "QB SPECIAL" FUNCTIONS JUMP TABLE
QBSPCTB	EQU	$-3*SPECBOT	;GET "VIRTUAL ORIGIN" OF TABLE
	JMP	MVLEFT		;--> MOVE LEFT TO RIGHT
	JMP	MVRIGHT		;--> MOVE RIGHT TO LEFT
	JMP	ZORANGE		;--> ZORANGE MONITOR (AT 0F000H)
	JMP	$		;EMPTY TABLE SLOTS
	JMP	$		;...
	JMP	$		;...
	JMP	$		;...
	JMP	$		;...
	JMP	$		;...
	JMP	$		;...

ZORANGE	EQU	0F000H		;ADDRESS OF ZORANGE MONITOR (IF PRESENT)

; MVLEFT, MVRIGHT
; "QB SPECIAL" FUNCTIONS TO MOVE BYTES
; PARAMETERS:
;    HL=SOURCE WORD ADDRESS
;    ZY=SOURCE BYTE OFFSET
;    DE=DESTINATION WORD ADDRESS
;    ZX=DESTINATION BYTE OFFSET
;    BC=NUMBER OF BYTES TO MOVE

MVLEFT	EQU	$
	CALL	MVADDR		;CALCULATE MOVE ADDRESSES, USE MEMORY MAP IF NECESSARY
	DW	LDIR		;Z80 LDIR TO DO THE MOVE
	RET			;-----> RETURN

MVRIGHT	EQU	$
	CALL	MVADDR		;CALCULATE MOVE ADDRESSES, USE MEMORY MAP IF NECESSARY
	DAD	B		;POINT TO ENDS OF STRINGS
	XCHG
	DAD	B
	XCHG
	DCX	H
	DCX	D
	DW	LDDR		;Z80 LDDR TO DO THE MOVE
	RET			;-----> RETURN

; MVADDR
; SUBROUTINE TO CALCULATE MOVE ADDRESSES FOR MVLEFT AND MVRIGHT
; INPUTS: SAME AS MVLEFT AND MVRIGHT
; OUTPUTS:
;	HL:=2*HL+ZY
;	DE:=2*DE+ZX
; CURRENTLY THIS IS A 64K OR LESS VERSION. FOR LARGER SYSTEMS, MUST
; CHECK FOR OVERFLOW IN THE CALCULATIONS AND USE MEMORY MAP IF NECESSARY

MVADDR	EQU	$
	PUSH	H		;SAVE HL
	LHLD	ZX		;HL:=2*DE+ZX (NEW DE)
	DAD	D		;...
	DAD	D		;...
	POP	D		;GET BACK ORIGINAL HL
	PUSH	H		;SAVE NEW DE
	LHLD	ZY		;HL:=2*HL+ZY
	DAD	D		;...
	DAD	D		;...
	POP	D		;GET BACK NEW DE
	RET			;-----> RETURN



	
